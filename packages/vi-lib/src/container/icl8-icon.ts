  private reader: VirtualFile;
  public width = 32;
  public height = 32;
  public bitPerPixel = 8;

  constructor(reader: VirtualFile) {
    super();
    this.reader = reader;
  }

  public getRGBA(): Uint8ClampedArray | null {
    this.reader.seek(0);

    const count = this.width * this.height;
    const out = new Uint8ClampedArray(count * 4);

    const pal: number[] = Icl8Icon.ColorPalette256;

    for (let i = 0; i < count; i++) {
      if (this.reader.eof()) {
        break;
      }

      const idx = this.reader.readByte();
      const color = pal[idx] ?? 0;
      const r = (color >> 16) & 0xff;
      const g = (color >> 8) & 0xff;
      const b = color & 0xff;
      const base = i * 4;
      out[base] = r;
      out[base + 1] = g;
      out[base + 2] = b;
      out[base + 3] = 255;
    }

    return out;
  }
